#!/usr/bin/env python3
"""Import SearXNG's declarative engines (`engine: xpath`, `json_engine`,
`mediawiki`) from upstream `searx/settings.yml` into our `settings.toml`.

The Rust port implements those three engine types generically (they read the
same settings keys as upstream), so the engine definitions can be carried over
verbatim instead of being rewritten by hand.

Usage:
    python3 tools/import_engines.py /path/to/searxng [settings.toml]

The script is idempotent: everything between the BEGIN/END markers is replaced.
Names or shortcuts that already exist in the file are skipped (the hand written
port of that engine wins).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

BEGIN = "# --- imported declarative engines (generated by tools/import_engines.py) ---"
END = "# --- end of imported declarative engines ---"

DECLARATIVE = {"xpath", "json_engine", "mediawiki"}

XPATH_KEYS = (
    "search_url", "method", "request_body", "results_xpath", "url_xpath",
    "title_xpath", "content_xpath", "thumbnail_xpath", "suggestion_xpath",
    "url_prefix", "first_page_num", "time_range_url", "time_range_map",
    "safesearch_map", "headers", "cookies",
)
JSON_KEYS = (
    "search_url", "method", "request_body", "results_query", "url_query",
    "title_query", "content_query", "thumbnail_query", "url_prefix",
    "thumbnail_prefix", "content_html_to_text", "title_html_to_text",
    "page_size", "first_page_num", "send_page_num_on_first_page",
    "time_range_url", "time_range_map", "headers", "cookies", "language_all",
)
MEDIAWIKI_KEYS = (
    "base_url", "search_type", "srenablerewrites", "srsort", "srprop",
    "page_size", "api_path",
)
TOP_LEVEL_BOOLS = ("paging", "time_range_support", "safesearch", "language_support")
TOP_LEVEL_NUMBERS = ("weight", "timeout")
TOP_LEVEL_STRINGS = ("base_url", "search_url", "api_key")


def toml_string(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, dict):
        inner = ", ".join(f"{toml_string(str(k))} = {toml_value(v)}" for k, v in value.items())
        return "{ " + inner + " }"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    return toml_string(str(value))


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    source = Path(sys.argv[1])
    target = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("settings.toml")
    upstream = yaml.safe_load((source / "searx" / "settings.yml").read_text(encoding="utf-8"))
    current = target.read_text(encoding="utf-8")
    if BEGIN in current and END in current:
        head, _, rest = current.partition(BEGIN)
        _, _, tail = rest.partition(END)
        current = head + tail
    names = set(re.findall(r'^name = "([^"]+)"', current, flags=re.M))
    shortcuts = set(re.findall(r'^shortcut = "([^"]+)"', current, flags=re.M))

    blocks = []
    imported = skipped = 0
    for engine in upstream.get("engines", []):
        kind = engine.get("engine")
        if kind not in DECLARATIVE or engine.get("inactive"):
            continue
        name = engine.get("name")
        if not name or name in names:
            skipped += 1
            continue
        keys = XPATH_KEYS if kind == "xpath" else JSON_KEYS if kind == "json_engine" else MEDIAWIKI_KEYS
        lines = ["[[engines]]", f"name = {toml_string(name)}", f'engine = {toml_string(kind)}']
        shortcut = engine.get("shortcut")
        if shortcut and shortcut not in shortcuts:
            shortcuts.add(shortcut)
            lines.append(f"shortcut = {toml_string(str(shortcut))}")
        categories = engine.get("categories")
        if categories:
            lines.append("categories = " + toml_value(list(categories)))
        for flag in TOP_LEVEL_BOOLS:
            if flag in engine:
                lines.append(f"{flag} = {toml_value(engine[flag])}")
        for key in TOP_LEVEL_NUMBERS:
            if key in engine:
                lines.append(f"{key} = {toml_value(engine[key])}")
        for key in ("base_url", "search_url", "api_key"):
            if key in engine and engine[key]:
                lines.append(f"{key} = {toml_value(str(engine[key]))}")
        if engine.get("disabled"):
            lines.append("disabled = true")
        for key in keys:
            if key not in engine:
                continue
            value = engine[key]
            if key in ("base_url", "search_url", "method", "request_body"):
                continue
            lines.append(f"{key} = {toml_value(value)}")
        blocks.append("\n".join(lines))
        names.add(name)
        imported += 1

    section = ["", BEGIN, f"# {imported} engines imported from SearXNG settings.yml", ""]
    section.extend(blocks)
    section.extend(["", END, ""])
    header = ""
    if not current.startswith("#"):
        header = ""
    target.write_text(current.rstrip("\n") + "\n" + "\n".join(section), encoding="utf-8")
    print(f"imported {imported} engines, skipped {skipped} (name already ported), wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
